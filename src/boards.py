def display_brd(brd: BoardData) -> None:
    for row_num, row in enumerate(brd, start=1):
        print(" ".join(str(value) for value in row[:3]), "|",
              " ".join(str(value) for value in row[3:6]), "|",
              " ".join(str(value) for value in row[6:]))
        if row_num in (3, 6):
            print("---------------------")


